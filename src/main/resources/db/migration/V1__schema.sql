-- Lets a GiST index combine "=" on bigint with "&&" on ranges.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE dealership (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      text NOT NULL,
    zone_id   text NOT NULL,
    opens_at  time NOT NULL,
    closes_at time NOT NULL,
    CONSTRAINT dealership_hours_valid CHECK (closes_at > opens_at)
);

CREATE TABLE service_bay (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id bigint NOT NULL REFERENCES dealership (id),
    name          text NOT NULL
);

CREATE TABLE technician (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id bigint NOT NULL REFERENCES dealership (id),
    name          text NOT NULL
);

CREATE TABLE service_type (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text NOT NULL,
    duration_minutes integer NOT NULL,
    CONSTRAINT service_type_duration_valid CHECK (duration_minutes BETWEEN 1 AND 480)
);

CREATE TABLE technician_skill (
    technician_id   bigint NOT NULL REFERENCES technician (id),
    service_type_id bigint NOT NULL REFERENCES service_type (id),
    PRIMARY KEY (technician_id, service_type_id)
);

CREATE TABLE customer (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL
);

CREATE TABLE vehicle (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES customer (id),
    registration text NOT NULL,
    CONSTRAINT vehicle_registration_unique UNIQUE (registration)
);

-- end_at is stored because a constraint cannot read service_type.
-- tstzrange is [start, end), so back-to-back appointments do not overlap.
CREATE TABLE appointment (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealership_id   bigint NOT NULL REFERENCES dealership (id),
    vehicle_id      bigint NOT NULL REFERENCES vehicle (id),
    service_type_id bigint NOT NULL REFERENCES service_type (id),
    technician_id   bigint NOT NULL REFERENCES technician (id),
    bay_id          bigint NOT NULL REFERENCES service_bay (id),
    start_at        timestamptz NOT NULL,
    end_at          timestamptz NOT NULL,
    status          text NOT NULL,
    CONSTRAINT appointment_time_valid CHECK (end_at > start_at),
    CONSTRAINT appointment_status_valid CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT appointment_technician_no_overlap
        EXCLUDE USING gist (technician_id WITH =, tstzrange(start_at, end_at) WITH &&)
        WHERE (status = 'CONFIRMED'),
    CONSTRAINT appointment_bay_no_overlap
        EXCLUDE USING gist (bay_id WITH =, tstzrange(start_at, end_at) WITH &&)
        WHERE (status = 'CONFIRMED'),
    CONSTRAINT appointment_vehicle_no_overlap
        EXCLUDE USING gist (vehicle_id WITH =, tstzrange(start_at, end_at) WITH &&)
        WHERE (status = 'CONFIRMED')
);
